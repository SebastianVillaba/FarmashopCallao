DECLARE @cambios TABLE (accion VARCHAR(10));

MERGE dbo.web_producto AS w
USING (
    SELECT l.idProducto, l.precio
    FROM @lista l
    INNER JOIN dbo.producto p ON p.idProducto = l.idProducto
) AS src
ON w.idProducto = src.idProducto
WHEN MATCHED AND w.precioRecomendado IS NULL
             AND (w.precioFarmashop IS NULL OR w.precioFarmashop < src.precio) THEN
    UPDATE SET precioRecomendado = src.precio, fechaMod = SYSDATETIME()
WHEN NOT MATCHED BY TARGET THEN
    INSERT (idProducto, precioRecomendado) VALUES (src.idProducto, src.precio)
OUTPUT $action INTO @cambios;

SELECT
    SUM(CASE WHEN accion = 'INSERT' THEN 1 ELSE 0 END) AS productosNuevos,
    SUM(CASE WHEN accion = 'UPDATE' THEN 1 ELSE 0 END) AS productosActualizados,
    (SELECT COUNT(*) FROM @lista) - COUNT(*) AS omitidos
FROM @cambios;
GO
